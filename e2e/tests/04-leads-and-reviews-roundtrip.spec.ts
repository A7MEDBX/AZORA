import { expect, test } from '@playwright/test';
import { fieldByLabel } from './helpers/adminUi';
import { E2E_CONFIG, E2ERunTracker } from './helpers/e2eContext';

test.describe('04 — Customer Submissions (Inquiries & Trip Plans) & Reviews Moderation Round-Trip', () => {
  const tracker = new E2ERunTracker('LEADS');

  test.afterAll(async ({ request }) => {
    await tracker.cleanupAll(request);
  });

  test('Submits Contact Inquiry & Trip Plan on Web, manages & deletes in Admin, and moderates Reviews live', async ({
    browser,
    request,
  }) => {
    const webContext = await browser.newContext();
    const adminContext = await browser.newContext();
    const webPage = await webContext.newPage();
    const adminPage = await adminContext.newPage();

    const inquiryEmail = `${tracker.slugPrefix}-contact@example.com`;
    const tripPlanEmail = `${tracker.slugPrefix}-planner@example.com`;
    const reviewerName = `${tracker.runId} Lady Evelyn`;
    const reviewTitle = `${tracker.runId} Dahabiya Voyage`;

    try {
      // Log into Admin first so tracker holds the admin JWT even if an assertion fails mid-test
      await tracker.loginViaAdminUi(adminPage);

      // 1. Submit Contact Inquiry on :3000/contact -> Verify 201 Created
      await webPage.goto(`${E2E_CONFIG.webBaseUrl}/contact`);
      await webPage.getByPlaceholder('e.g. Lord Harrington').fill(`${tracker.runId} Guest`);
      await webPage.getByPlaceholder('harrington@example.com').fill(inquiryEmail);
      await webPage.getByPlaceholder('+1 (555) 019-2834').fill('+20 100 555 0199');
      await webPage
        .getByPlaceholder('How may we assist your upcoming voyage to Egypt?')
        .fill(`Bespoke private charter inquiry generated by ${tracker.runId}.`);

      const inquiryPostPromise = webPage.waitForResponse(
        (res) => res.url().includes('/api/inquiries') && res.request().method() === 'POST'
      );
      await webPage.getByRole('button', { name: 'Send Message' }).click();
      const inquiryPostRes = await inquiryPostPromise;
      expect(inquiryPostRes.status()).toBe(201);
      const inquiryJson = (await inquiryPostRes.json()) as { data: { id: string } };
      tracker.trackEntity('inquiries', inquiryJson.data.id);

      await expect(webPage.getByRole('heading', { name: 'Message Received' })).toBeVisible();

      // 2. Complete & Submit Trip Planner Wizard on :3000/plan-your-trip -> Verify 201 & Ref ID
      await webPage.goto(`${E2E_CONFIG.webBaseUrl}/plan-your-trip`);
      // Step 1 -> Step 2 (default destinations cairo-giza & luxor are preselected)
      await webPage.getByRole('button', { name: /Continue to Step 2/i }).click();
      // Step 2 -> Step 3
      await webPage.getByRole('button', { name: /Continue to Step 3/i }).click();
      // Step 3 -> Step 4
      await webPage.getByRole('button', { name: /Continue to Step 4/i }).click();
      // Step 4 -> Step 5 (default interests are preselected)
      await webPage.getByRole('button', { name: /Continue to Step 5/i }).click();
      // Step 5 -> Step 6
      await webPage.getByRole('button', { name: /Continue to Step 6/i }).click();
      // Step 6: Contact Details
      await webPage
        .getByPlaceholder('e.g. Lord Charles Sterling')
        .fill(`${tracker.runId} Traveler`);
      await webPage.getByPlaceholder('e.g. sterling@luxuryvoyage.com').fill(tripPlanEmail);
      await webPage.getByPlaceholder('+44 7911 123456').fill('+44 7911 999888');
      await webPage.getByPlaceholder('United Kingdom / United States').fill('United Kingdom');
      await webPage.getByRole('button', { name: /Continue to Step 7/i }).click();

      // Step 7: Submit
      const tripPlanPostPromise = webPage.waitForResponse(
        (res) => res.url().includes('/api/trip-plans') && res.request().method() === 'POST'
      );
      await webPage.getByRole('button', { name: /Submit Bespoke Inquiry/i }).click();
      const tripPlanPostRes = await tripPlanPostPromise;
      expect(tripPlanPostRes.status()).toBe(201);
      const tripPlanJson = (await tripPlanPostRes.json()) as { data: { id: string } };
      tracker.trackEntity('trip-plans', tripPlanJson.data.id);

      await expect(
        webPage.getByRole('heading', { name: 'Bespoke Journey Requested' })
      ).toBeVisible();
      await expect(webPage.getByText(/Inquiry Reference:\s*VOE-/i)).toBeVisible();

      // 3. Admin Inquiries (:5174/inquiries): Search -> Open Modal -> Update Status -> Reload -> Delete
      await adminPage.goto(`${E2E_CONFIG.adminBaseUrl}/inquiries`);
      await adminPage.getByPlaceholder('Search name, email, or subject...').fill(inquiryEmail);
      const inqRow = adminPage
        .locator('table.data-table tbody tr')
        .filter({ hasText: inquiryEmail })
        .first();
      await expect(inqRow).toBeVisible();
      await inqRow.click();

      const inqModal = adminPage.locator('.modal-card').first();
      await expect(inqModal).toContainText(inquiryEmail);
      await inqModal.locator('select').selectOption('in_progress');
      await expect(adminPage.locator('.toast-success')).toContainText(/in progress/i);

      await adminPage.reload();
      await adminPage.getByPlaceholder('Search name, email, or subject...').fill(inquiryEmail);
      const reloadedInqRow = adminPage
        .locator('table.data-table tbody tr')
        .filter({ hasText: inquiryEmail })
        .first();
      await expect(reloadedInqRow.locator('.badge')).toHaveText(/in progress/i);

      await reloadedInqRow.click();
      await adminPage.locator('.modal-card').first().getByRole('button', { name: /Delete/i }).click();
      const confirmInqDelete = adminPage.locator('.modal-card').last();
      await confirmInqDelete.getByRole('button', { name: /^Delete$/ }).click();
      await expect(
        adminPage.locator('table.data-table tbody tr').filter({ hasText: inquiryEmail })
      ).toHaveCount(0);
      tracker.untrackEntity('inquiries', inquiryJson.data.id);

      // 4. Admin Trip Plans (:5174/trip-plans): Search -> Open Modal -> Update Status -> Reload -> Delete
      await adminPage.goto(`${E2E_CONFIG.adminBaseUrl}/trip-plans`);
      await adminPage.getByPlaceholder('Search traveler name or email...').fill(tripPlanEmail);
      const planRow = adminPage
        .locator('table.data-table tbody tr')
        .filter({ hasText: tripPlanEmail })
        .first();
      await expect(planRow).toBeVisible();
      await planRow.click();

      const planModal = adminPage.locator('.modal-card').first();
      await expect(planModal).toContainText(tripPlanEmail);
      await planModal.locator('select').selectOption('reviewing');
      await expect(adminPage.locator('.toast-success')).toContainText(/reviewing/i);

      await adminPage.reload();
      await adminPage.getByPlaceholder('Search traveler name or email...').fill(tripPlanEmail);
      const reloadedPlanRow = adminPage
        .locator('table.data-table tbody tr')
        .filter({ hasText: tripPlanEmail })
        .first();
      await expect(reloadedPlanRow.locator('.badge')).toHaveText(/reviewing/i);

      await reloadedPlanRow.click();
      await adminPage
        .locator('.modal-card')
        .first()
        .getByRole('button', { name: /Delete/i })
        .click();
      const confirmPlanDelete = adminPage.locator('.modal-card').last();
      await confirmPlanDelete.getByRole('button', { name: /^Delete$/ }).click();
      await expect(
        adminPage.locator('table.data-table tbody tr').filter({ hasText: tripPlanEmail })
      ).toHaveCount(0);
      tracker.untrackEntity('trip-plans', tripPlanJson.data.id);

      // 5. Admin Reviews Moderation (:5174/reviews): Create Unapproved -> Verify Hidden -> Approve -> Verify Public -> Delete
      await adminPage.goto(`${E2E_CONFIG.adminBaseUrl}/reviews`);
      await adminPage.getByRole('button', { name: /Add Verified Review/i }).click();

      const reviewModal = adminPage.locator('.modal-card');
      await fieldByLabel(reviewModal.page(), /^Reviewer Name/).locator('input').fill(reviewerName);
      await fieldByLabel(reviewModal.page(), 'Country / Location')
        .locator('input')
        .fill('Edinburgh, UK');
      await fieldByLabel(reviewModal.page(), /^Title/)
        .locator('input')
        .fill(reviewTitle);
      await fieldByLabel(reviewModal.page(), /^Review Content/)
        .locator('textarea')
        .fill(`Unforgettable private Egyptologist curatorial tour (${tracker.runId}).`);

      // Uncheck "Approved (Public)" so it starts as unapproved
      const approvedCheckbox = reviewModal.locator('input[type="checkbox"]');
      if (await approvedCheckbox.isChecked()) {
        await approvedCheckbox.uncheck();
      }

      const createReviewPromise = adminPage.waitForResponse(
        (res) => res.url().includes('/api/admin/reviews') && res.request().method() === 'POST'
      );
      await reviewModal.getByRole('button', { name: 'Create Review' }).click();
      const createReviewRes = await createReviewPromise;
      expect(createReviewRes.status()).toBe(201);
      const createdReviewJson = (await createReviewRes.json()) as { data: { id: string } };
      tracker.trackEntity('reviews', createdReviewJson.data.id);

      // Verify unapproved review does NOT appear in public GET /api/reviews
      const publicBeforeRes = await request.get(`${E2E_CONFIG.apiBaseUrl}/reviews`);
      const publicBeforeJson = (await publicBeforeRes.json()) as {
        data: { author: string }[];
      };
      expect(publicBeforeJson.data.some((r) => r.author === reviewerName)).toBe(false);

      // Click Approve in Admin UI
      const reviewCard = adminPage
        .locator('div[style*="border: 1px solid"]')
        .filter({ hasText: reviewerName })
        .first();
      await expect(reviewCard).toBeVisible();
      await reviewCard.getByRole('button', { name: /^Approve$/i }).click();
      await expect(reviewCard.locator('.badge-published')).toHaveText(/Approved/i);

      // Verify approved review DOES appear in GET /api/reviews AND on public :3000/about
      const publicAfterRes = await request.get(`${E2E_CONFIG.apiBaseUrl}/reviews`);
      const publicAfterJson = (await publicAfterRes.json()) as {
        data: { author: string }[];
      };
      expect(publicAfterJson.data.some((r) => r.author === reviewerName)).toBe(true);

      await webPage.goto(`${E2E_CONFIG.webBaseUrl}/about`);
      await expect(webPage.getByText(reviewerName)).toBeVisible();

      // Delete the E2E review via Admin UI
      await reviewCard.locator('button[aria-label="Delete review"]').click();
      const confirmReviewDelete = adminPage.locator('.modal-card');
      await confirmReviewDelete.getByRole('button', { name: /^Delete$/ }).click();
      await expect(
        adminPage.locator('div[style*="border: 1px solid"]').filter({ hasText: reviewerName })
      ).toHaveCount(0);
      tracker.untrackEntity('reviews', createdReviewJson.data.id);
    } finally {
      await webContext.close();
      await adminContext.close();
    }
  });
});
